from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from enum import StrEnum
from typing import NoReturn

from pipelines.bronze.columns import MetadataColumn
from pipelines.schemas.definitions import ColumnDefinition, EntityDefinition
from pipelines.schemas.gold_definitions import GoldTable

INTERNAL_SCHEMA = "gold_internal"
STAGING_PREFIX = "stage_"
STAGING_DESCRIPTION = (
    "Versions of the micro-batch being written to {table}, loaded by Spark and replaced by"
    " every batch; unlogged, so it may be empty after a crash"
)


class Scd2Column(StrEnum):
    COMMIT_SEQUENCE = "_commit_sequence"
    CONTENT_HASH = "_content_hash"
    IS_DELETED = "_is_deleted"
    IS_FOLDED = "_is_folded"
    VALID_FROM = "_valid_from"
    VALID_TO = "_valid_to"
    IS_CURRENT = "_is_current"


RECOMPUTED_COLUMNS = (Scd2Column.IS_FOLDED, Scd2Column.VALID_TO, Scd2Column.IS_CURRENT)
SILVER_COLUMNS: Mapping[str, str] = {Scd2Column.VALID_FROM: str(MetadataColumn.CHANGED_AT)}


class Scd2DefinitionError(ValueError):
    def __init__(self, table: str, problem: str) -> None:
        super().__init__(f"SCD2 dimension {table}: {problem}")


def _lines(items: Iterable[str], indent: str = "    ") -> str:
    return ",\n".join(f"{indent}{item}" for item in items)


@dataclass(frozen=True, slots=True)
class Scd2Dimension:
    """An SCD2 dimension in gold_internal, loaded from the silver table of one source entity.

    Every column comes from the silver column its `from` names (`<entity>.<lake name>`), a
    metadata column from the silver column of the same name, and `_valid_from` from
    `_changed_at`; `renamed` gives the silver column of any other gold column, as
    (gold column, silver column) pairs. `surrogate_key` is generated by the database.
    """

    table: GoldTable
    entity: EntityDefinition
    surrogate_key: str
    renamed: tuple[tuple[str, str], ...] = ()

    def __post_init__(self) -> None:
        required = {self.surrogate_key, *Scd2Column}
        missing = sorted(required - {column.name for column in self.table.columns})
        if missing:
            self._fail(f"the table has no columns named {', '.join(missing)}")
        self._key()

    def _fail(self, problem: str) -> NoReturn:
        raise Scd2DefinitionError(self.table.name, problem)

    @property
    def name(self) -> str:
        return self.table.name

    @property
    def relation(self) -> str:
        return f"{INTERNAL_SCHEMA}.{self.name}"

    @property
    def staging_relation(self) -> str:
        return f"{INTERNAL_SCHEMA}.{self.staging_table.name}"

    @property
    def staged_columns(self) -> tuple[ColumnDefinition, ...]:
        """The columns loaded from silver: all but the surrogate key and the recomputed ones."""
        derived = {self.surrogate_key, *RECOMPUTED_COLUMNS}
        return tuple(column for column in self.table.columns if column.name not in derived)

    @property
    def staging_table(self) -> GoldTable:
        return GoldTable(
            name=f"{STAGING_PREFIX}{self.name}",
            description=STAGING_DESCRIPTION.format(table=f"{INTERNAL_SCHEMA}.{self.name}"),
            columns=self.staged_columns,
        )

    def _silver_column(self, column: str) -> str | None:
        renamed = dict(self.renamed)
        if column in renamed:
            return renamed[column]
        if column in SILVER_COLUMNS:
            return SILVER_COLUMNS[column]
        reference = self.table.reference(column)
        if reference is None:
            return column if column.startswith("_") else None
        owner, _, lake_name = reference.partition(".")
        return lake_name if owner == self.entity.name else None

    @property
    def silver_columns(self) -> Mapping[str, str]:
        """The silver column each staged column is loaded from, by gold column."""
        return self._sources()

    def _sources(self) -> Mapping[str, str]:
        staged = [column.name for column in self.staged_columns]
        unknown = sorted(set(dict(self.renamed)) - set(staged))
        if unknown:
            self._fail(f"renamed names columns it does not stage: {', '.join(unknown)}")
        sources = {column: self._silver_column(column) for column in staged}
        unmapped = [column for column, source in sources.items() if source is None]
        if unmapped:
            self._fail(
                f"no silver column of {self.entity.name} for {', '.join(unmapped)};"
                " give it a from or a rename"
            )
        return {column: source for column, source in sources.items() if source is not None}

    @property
    def key(self) -> str:
        """The gold column loaded from the entity's key, which identifies a row's versions."""
        return self._key()

    def _key(self) -> str:
        (entity_key,) = (c for c in self.entity.columns if c.name == self.entity.key)
        lake_name = entity_key.lake_name
        keys = [gold for gold, silver in self._sources().items() if silver == lake_name]
        if len(keys) != 1:
            self._fail(f"exactly one column must come from {self.entity.name}.{entity_key.name}")
        return keys[0]

    def check_silver(self, columns: Iterable[str]) -> None:
        """Fail if the silver input lacks a column the dimension is loaded from."""
        missing = sorted(set(self.silver_columns.values()) - set(columns))
        if missing:
            self._fail(f"the silver input has no columns named {', '.join(missing)}")

    def insert_statement(self) -> str:
        """Insert the staged versions not stored yet, not current until they are recomputed."""
        staged = [column.name for column in self.staged_columns]
        targets = [*staged, Scd2Column.IS_FOLDED, Scd2Column.IS_CURRENT]
        return (
            f"INSERT INTO {self.relation} (\n{_lines(targets)}\n)\n"
            f"SELECT\n{_lines([*staged, 'false', 'false'])}\n"
            f"FROM {self.staging_relation}\n"
            f"ON CONFLICT ({self.key}, {Scd2Column.COMMIT_SEQUENCE}) DO NOTHING"
        )

    def _recomputed(self) -> str:
        """The fold flag, `_valid_to` and `_is_current` of every stored version of each key the
        staged batch touches, from all of the key's versions in `_commit_sequence` order.

        A version is folded when its content hash and deletion state equal the previous
        version's; the first version's lag is null and its hash is not, so it never is. Folded
        versions share the number of the version they repeat, so they end when it ends.
        """
        key, surrogate = self.key, self.surrogate_key
        sequence, content_hash = Scd2Column.COMMIT_SEQUENCE, Scd2Column.CONTENT_HASH
        valid_from, valid_to = Scd2Column.VALID_FROM, Scd2Column.VALID_TO
        deleted, folded, current = (
            Scd2Column.IS_DELETED,
            Scd2Column.IS_FOLDED,
            Scd2Column.IS_CURRENT,
        )
        by_key = f"PARTITION BY {key} ORDER BY {sequence}"
        return f"""WITH flagged AS (
    SELECT
        {surrogate},
        {key},
        {sequence},
        {valid_from},
        {deleted},
        ({content_hash}, {deleted}) IS NOT DISTINCT FROM
            (lag({content_hash}) OVER by_key, lag({deleted}) OVER by_key) AS {folded}
    FROM {self.relation}
    WHERE {key} IN (SELECT {key} FROM {self.staging_relation})
    WINDOW by_key AS ({by_key})
),
numbered AS (
    SELECT
        *,
        count(*) FILTER (WHERE NOT {folded}) OVER by_key AS version_number
    FROM flagged
    WINDOW by_key AS ({by_key})
),
versions AS (
    SELECT
        {key},
        version_number,
        lead({valid_from}) OVER by_version AS {valid_to},
        lead(version_number) OVER by_version IS NULL AND NOT {deleted} AS {current}
    FROM numbered
    WHERE NOT {folded}
    WINDOW by_version AS (PARTITION BY {key} ORDER BY version_number)
),
recomputed AS (
    SELECT
        numbered.{surrogate},
        numbered.{folded},
        versions.{valid_to},
        versions.{current} AND NOT numbered.{folded} AS {current}
    FROM numbered
    JOIN versions USING ({key}, version_number)
)"""

    def _update(self, condition: str) -> str:
        assignments = [f"{column} = recomputed.{column}" for column in RECOMPUTED_COLUMNS]
        return (
            f"{self._recomputed()}\n"
            f"UPDATE {self.relation} AS stored\n"
            f"SET\n{_lines(assignments)}\n"
            "FROM recomputed\n"
            f"WHERE stored.{self.surrogate_key} = recomputed.{self.surrogate_key}\n"
            f"  AND {condition}"
        )

    def close_statement(self) -> str:
        """Apply the recomputed values to the current versions that stop being current.

        It runs before the other updates because the unique index on current versions is
        checked row by row, so a key's old current version must be closed first.
        """
        current = Scd2Column.IS_CURRENT
        return self._update(f"stored.{current} AND NOT recomputed.{current}")

    def recompute_statement(self) -> str:
        """Apply the recomputed values to every other version whose values change."""
        stored = ", ".join(f"stored.{column}" for column in RECOMPUTED_COLUMNS)
        recomputed = ", ".join(f"recomputed.{column}" for column in RECOMPUTED_COLUMNS)
        return self._update(f"({stored})\n      IS DISTINCT FROM ({recomputed})")

    def merge_statements(self) -> Sequence[str]:
        """The statements that merge the staged batch, to run in this order in one transaction."""
        return (self.insert_statement(), self.close_statement(), self.recompute_statement())
