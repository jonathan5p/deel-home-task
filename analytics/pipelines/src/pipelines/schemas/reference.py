import argparse
import sys
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from importlib.resources.abc import Traversable
from pathlib import Path

from pipelines.schemas.definitions import (
    POSTGRES_TYPES,
    SCHEMAS,
    ColumnDefinition,
    ColumnType,
    EntityDefinition,
    TableTemplate,
    load_entities,
    load_table_templates,
)
from pipelines.schemas.gold_definitions import GoldTable, load_gold_tables

PAGE_SUFFIX = ".md"
REGENERATE = "make docs-tables"

# Spark SQL type names, spelled out because the renderer runs on the host, where PySpark is not
# installed; a unit test checks them against pipelines.lake.types.SPARK_TYPES.
LAKE_TYPES: Mapping[ColumnType, str] = {
    ColumnType.LONG: "bigint",
    ColumnType.INT: "int",
    ColumnType.STRING: "string",
    ColumnType.BOOLEAN: "boolean",
    ColumnType.TIMESTAMP_MILLIS: "timestamp",
    ColumnType.DATE: "date",
    ColumnType.DECIMAL: "decimal(38,10)",
}

GENERATED_NOTE = (
    f"<!-- Generated by `{REGENERATE}` from the schemas in"
    " analytics/pipelines/src/pipelines/schemas/. Do not edit by hand. -->"
)
LAKE_NULLABLE = (
    "**Type** is the Spark SQL type. **Nullable** `no` means the pipeline always writes a value;"
    " Iceberg itself declares every lake column nullable."
)
INTROS: Mapping[str, str] = {
    "bronze": (
        "Bronze holds one typed Iceberg table per source table, with one row per change event,"
        " and a quarantine table per source table for the records that fail validation."
        f" {LAKE_NULLABLE}"
    ),
    "silver": (
        "Silver holds one append-only Iceberg table of versions per source table, and two views"
        " over it: `<entity>_history`, the versions that changed the row with their validity"
        f" range, and `<entity>_current`, the latest version. {LAKE_NULLABLE}"
    ),
    "gold": (
        "Gold lives in the analytics PostgreSQL. Each relation below is a table in"
        " `gold_internal` with a view of the same name in `gold`, or a view in `gold` only."
        " The public views leave out pipeline metadata such as `_commit_sequence` and"
        " `_is_deleted`; [the gold model](../../architecture/gold-model.md) describes what each"
        " view shows. **Type** is the PostgreSQL type, and **Nullable** `no` means `NOT NULL`."
    ),
}
TITLES: Mapping[str, str] = {
    "bronze": "Bronze tables",
    "silver": "Silver tables and views",
    "gold": "Gold tables and views",
}
LAKE_LAYERS = ("bronze", "silver")
GOLD = "gold"


@dataclass(frozen=True, slots=True)
class ReferenceColumn:
    name: str
    type: str
    nullable: bool
    description: str


@dataclass(frozen=True, slots=True)
class Relation:
    name: str
    description: str
    columns: tuple[ReferenceColumn, ...]
    notes: tuple[str, ...] = ()


@dataclass(frozen=True, slots=True)
class ReferencePage:
    layer: str
    relations: tuple[Relation, ...]

    @property
    def file_name(self) -> str:
        return f"{self.layer}{PAGE_SUFFIX}"


def _column(
    column: ColumnDefinition, name: str, types: Mapping[ColumnType, str]
) -> ReferenceColumn:
    return ReferenceColumn(
        name=name,
        type=types[column.type],
        nullable=not column.not_null,
        description=column.description,
    )


def lake_relations(
    layer: str, templates: Iterable[TableTemplate], entities: Iterable[EntityDefinition]
) -> tuple[Relation, ...]:
    """Every table and view of a lake layer, one per template of the layer and entity, by name."""
    entities = tuple(entities)
    relations = [
        Relation(
            name=f"{layer}.{template.table_name(entity)}",
            description=template.describe(entity),
            columns=tuple(
                _column(column, column.lake_name, LAKE_TYPES)
                for column in template.columns_for(entity)
            ),
            notes=(
                (f"Partitioned by day of `{template.partitioned_by}`.",)
                if template.partitioned_by
                else ()
            ),
        )
        for template in templates
        if template.layer == layer
        for entity in entities
    ]
    return tuple(sorted(relations, key=lambda relation: relation.name))


def gold_relations(tables: Mapping[str, GoldTable]) -> tuple[Relation, ...]:
    """Every gold relation by name. A relation whose view has its own description also shows the
    description of its internal table."""
    return tuple(
        Relation(
            name=table.name,
            description=table.view_description,
            columns=tuple(_column(column, column.name, POSTGRES_TYPES) for column in table.columns),
            notes=(
                (f"Internal table `gold_internal.{table.name}`: {table.description}",)
                if table.public_description
                else ()
            ),
        )
        for _, table in sorted(tables.items())
    )


def reference_pages(root: Traversable = SCHEMAS) -> tuple[ReferencePage, ...]:
    templates = tuple(load_table_templates(root).values())
    entities = load_entities(root)
    lake = (
        ReferencePage(layer, lake_relations(layer, templates, entities)) for layer in LAKE_LAYERS
    )
    return (*lake, ReferencePage(GOLD, gold_relations(load_gold_tables(root))))


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _relation_text(relation: Relation) -> list[str]:
    lines = [f"## {relation.name}", "", _cell(relation.description), ""]
    for note in relation.notes:
        lines += [note, ""]
    lines += ["| Column | Type | Nullable | Description |", "| --- | --- | --- | --- |"]
    lines += [
        f"| `{column.name}` | {column.type} | {'yes' if column.nullable else 'no'}"
        f" | {_cell(column.description)} |"
        for column in relation.columns
    ]
    return [*lines, ""]


def render_page(page: ReferencePage) -> str:
    """The page as Markdown: a title, the layer's introduction, then one section per relation."""
    lines = [f"# {TITLES[page.layer]}", "", GENERATED_NOTE, "", INTROS[page.layer], ""]
    for relation in page.relations:
        lines += _relation_text(relation)
    return "\n".join(lines)


def rendered_files(pages: Iterable[ReferencePage]) -> dict[str, str]:
    return {page.file_name: render_page(page) for page in pages}


def _existing_files(out_dir: Path) -> dict[str, str]:
    if not out_dir.is_dir():
        return {}
    return {
        path.name: path.read_text(encoding="utf-8")
        for path in sorted(out_dir.glob(f"*{PAGE_SUFFIX}"))
    }


def stale_files(out_dir: Path, files: Mapping[str, str]) -> list[str]:
    """The pages under `out_dir` that are missing, differ from `files`, or are no longer
    rendered, by file name."""
    existing = _existing_files(out_dir)
    return sorted(
        name for name in set(existing) | set(files) if existing.get(name) != files.get(name)
    )


def write_files(out_dir: Path, files: Mapping[str, str]) -> None:
    """Write each page under `out_dir` and remove the pages that are no longer rendered."""
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (out_dir / name).write_text(text, encoding="utf-8")
    for name in set(_existing_files(out_dir)) - set(files):
        (out_dir / name).unlink()


def main(argv: Sequence[str]) -> None:
    parser = argparse.ArgumentParser(
        prog="python -m pipelines.schemas.reference",
        description="Write the Markdown table reference of every layer: <out_dir>/<layer>.md",
    )
    parser.add_argument("out_dir", type=Path)
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; fail if the pages in out_dir differ from the schemas",
    )
    arguments = parser.parse_args(argv)
    files = rendered_files(reference_pages())
    if not arguments.check:
        write_files(arguments.out_dir, files)
        return
    stale = stale_files(arguments.out_dir, files)
    if stale:
        raise SystemExit(
            f"{arguments.out_dir} is out of date with the schemas ({', '.join(stale)});"
            f" run {REGENERATE} and commit the result"
        )


if __name__ == "__main__":
    main(sys.argv[1:])
